"""Stage 3: status.json reproduces ONGA's (scratch tree: its baseline is
regenerated by ONGA's own scripts/curation_status.py)."""
from conftest import ADAPTER, strip_generated

from curation_workbench import status
from curation_workbench.workbench import Workbench


def test_status_matches(scratch):
    wb = Workbench.open(ADAPTER, root=scratch)
    text, summary = status.render(wb)
    want = (scratch / "curation" / "status.json").read_text()
    assert strip_generated(text) == strip_generated(want), summary
